const fs = require('fs');
const f = 'src/app/admin/page.tsx';
let s = fs.readFileSync(f, 'utf8');
const pairs = [
  ['상담원 연결 요청', '상담사 전환 요청'],
  ['상담원 요청', '상담사 전환 요청'],
  ['상담원 제안', '상담사 전환 제안'],
  ['상담원 연결하기', '상담사 전환하기'],
  ['상담원 연결', '상담사 전환'],
  ['상담원', '상담사'],
  ['내려받는 중', '다운로드 중'],
  ['내려받기', '다운로드'],
  ['내려받았습니다', '다운로드했습니다'],
  ['내려받지 못했습니다', '다운로드하지 못했습니다'],
  ['내려받을', '다운로드할'],
  ['내려받는', '다운로드하는'],
  ['시나리오 룰', '시나리오'],
  ['지식베이스', '답변 지식'],
];
for (const [a, b] of pairs) s = s.split(a).join(b);
fs.writeFileSync(f, s, 'utf8');
