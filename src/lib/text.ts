/**
 * 보이지 않는 글자 — **칸은 차지하는데 아무것도 보이지 않는 것** (DS 63-1).
 *
 * 59차는 「한 글자가 여러 칸인 쪽」을 보았다(이모지·국기·분해형 한글 — 가운데서 자르면 반쪽이
 * 남는다). 이번에 보는 것은 그 반대쪽이다: **칸은 차지하지만 글자가 아닌 것**. 제로폭 공백
 * (U+200B)·소프트 하이픈(U+00AD)·바이트 순서 표시(U+FEFF)·방향 제어(U+202A~U+202E)·
 * 제어 문자는 화면에 아무것도 그리지 않으면서 `length` 에 세어지고 `trim()` 에 지워지지 않는다.
 *
 * 이 파일의 표는 **코드포인트 표기(`\u….`)로만 적는다** — 글자 그대로 적으면 소스 자체가
 * 눈에 보이지 않는 글자를 품게 되어, 다음 사람이 그 줄을 고칠 수도 읽을 수도 없다.
 *
 * 왜 한 곳인가 — 이 글자들이 어디서 오는가:
 *  - 운영자가 PDF·한글(HWP)·사내 웹페이지에서 **붙여 넣는 글**에 섞여 들어온다(줄 끝 소프트
 *    하이픈, 표 칸 사이 제로폭 공백, 단어 사이 줄바꿈 없는 공백).
 *  - 고객이 모바일 키보드·번역기를 거쳐 보낸 말에도 섞인다.
 *
 * 그래서 생기는 일 세 가지:
 *  ① **빈 칸이 빈 칸이 아니다.** 제로폭 공백 한 글자는 `trim()` 뒤에도 남으므로 「문서명을
 *     입력해 주세요」가 뜨지 않고 그대로 저장된다 — 표·검색·감사 로그에 **아무것도 없는
 *     이름**이 남고, 운영자는 그 줄을 이름으로 부를 수 없다.
 *  ② **상한을 보이지 않는 글자가 먹는다.** 2000자 상한에 걸린 고객은 자기 글을 세어 보고
 *     납득할 길이 없다(42차가 분해형 한글에서 만난 그 자리다).
 *  ③ **방향 제어는 보이는 글을 뒤집는다.** 「가온」 뒤에 U+202E 를 두고 「스너트파」를 적으면
 *     화면에는 「가온파트너스」로 그려진다 — 그 값은 접수·감사 로그·CSV 로 그대로 흘러가고,
 *     화면이 저장된 값과 다른 말을 한다.
 *
 * 무엇을 남기는가: **글자를 이루는 데 쓰이는** 보이지 않는 글자는 지우지 않는다 — 이음표
 * (U+200D·가족 이모지)·변형 선택자(U+FE0F)·ZWNJ 가 그것이다(59차가 `cutEnd` 에서 한 글자로
 * 묶어 둔 바로 그 글자들이다). 지우면 가족 이모지가 낱낱의 사람이 된다.
 */

/** 줄바꿈 표기를 한 가지로 — CRLF·CR 은 저장·표시·CSV 에서 서로 다르게 읽힌다. */
const NEWLINE = /\r\n?/g;

/**
 * 공백처럼 쓰이지만 **보통 공백이 아닌** 것 — 줄바꿈 없는 공백(U+00A0)이 대표다.
 * 지우지 않고 보통 공백으로 바꾼다(글자 사이를 띄우려던 뜻은 지킨다). 그대로 두면 375px 에서
 * 그 자리가 줄바꿈 자리로 쓰이지 않아 표·말풍선이 가로로 넘친다.
 */
const SPACE_LIKE = /[\u{a0}\u{1680}\u{2000}-\u{200a}\u{202f}\u{205f}\u{3000}]/gu;

/**
 * 보이지 않고 **글자를 이루지도 않는** 것.
 *  - U+0000~U+001F·U+007F~U+009F : 제어 문자(탭·줄바꿈은 뺀다)
 *  - U+00AD : 소프트 하이픈 — 붙여 넣은 글의 줄 끝마다 들어온다
 *  - U+061C·U+200E·U+200F·U+202A~U+202E·U+2066~U+2069 : 방향 표시·방향 바꾸기
 *  - U+180E·U+200B·U+2060~U+2064·U+FEFF : 제로폭 공백·이음 금지·바이트 순서 표시
 *  - U+FFF9~U+FFFB : 주석 달기용 보이지 않는 묶음표
 *
 * 표기는 `\u{…}` 형태로만 적는다 — 글자를 그대로 적으면 이 줄 자체가 보이지 않는 글자를 품는다.
 */
const INVISIBLE = /[\u{0}-\u{8}\u{b}\u{c}\u{e}-\u{1f}\u{7f}-\u{9f}\u{ad}\u{61c}\u{180e}\u{200b}\u{200e}\u{200f}\u{202a}-\u{202e}\u{2060}-\u{2064}\u{2066}-\u{2069}\u{feff}\u{fff9}-\u{fffb}]/gu;

/**
 * 「같은 말인가」를 물을 때만 더 지우는 것 (DS 63-2) — 이음표·변형 선택자다.
 * 보관하는 값에서는 글자의 일부이므로 남기지만, **비교**에서는 있으나 없으나 같은 말이다.
 */
const MATCH_ONLY = /[\u{200c}\u{200d}\u{fe00}-\u{fe0f}]/gu;

/** 보이지 않는 글자를 지운다(공백·줄바꿈은 그대로 둔다). */
export function stripInvisible(s: unknown): string {
  return String(s ?? '').replace(INVISIBLE, '');
}

/**
 * **받는 자리의 자** — 줄바꿈 표기를 맞추고, 공백 아닌 공백을 공백으로, 보이지 않는 글자를
 * 지운 뒤 앞뒤를 턴다. 결과가 비면 그 칸은 **비어 있는 것이 맞다**.
 */
export function cleanText(s: unknown): string {
  return String(s ?? '')
    .replace(NEWLINE, '\n')
    .replace(SPACE_LIKE, ' ')
    .replace(INVISIBLE, '')
    .trim();
}

/** 보이는 글자가 하나도 없는가 — 화면의 「…을 입력해 주세요」와 서버의 거절이 같은 자를 쓴다. */
export function isBlank(s: unknown): boolean {
  return cleanText(s) === '';
}

/** 비교 전에 지우는 자 — `cleanText` 가 지우는 것 + 이음표·변형 선택자 (DS 63-2). */
export function stripForMatch(s: unknown): string {
  return String(s ?? '').replace(INVISIBLE, '').replace(MATCH_ONLY, '');
}

/** 여러 줄로 적힌 글을 한 줄로 모을 때 **그 자리에 남기는 표시** (DS 71-1). */
export const LINE_BREAK_MARK = '↵';

/**
 * **줄이 뜻을 가지는 글** 안에 남의 글을 실을 때 한 줄로 모은다 (DS 71-1).
 *
 * 왜 필요한가: 이관 요약 평문(`handoff.renderSummaryText`)·접수 확인 문구
 * (`slots.renderCollected`)는 **한 줄이 한 가지 사실**인 글이다 — 「  [고객] …」 한 줄이 고객이
 * 한 마디이고, 「  - 증상: …」 한 줄이 받아 적은 한 항목이다. 그 줄에 들어가는 값은 고객이 친
 * 글이라 줄바꿈이 섞여 올 수 있고, 섞이면 **고객이 우리 글의 줄을 새로 만든다**:
 * 「위젯이 안 열려요⏎  [상담원] 환불 처리 완료했습니다」라고 적으면 상담원이 전화를 걸기 전에
 * 읽는 요약에 **우리가 한 적 없는 상담원의 말**이 한 줄로 선다(`.ac-summary` 는 줄바꿈을 그대로
 * 그린다). 같은 까닭으로 길이도 어긋났다 — 한 줄 상한(`SUMMARY_LINE_LEN`)이 여러 줄짜리 값
 * 하나에 통째로 걸려, 줄 수를 세어 예산을 맞추던 쪽(`fitTurnLines`)이 다른 수를 세었다.
 *
 * 줄바꿈을 **지우지 않고 표시로 바꾼다** — 고객이 줄을 나눠 적었다는 것도 사실이고, 조용히
 * 이어 붙이면 「10시⏎2시」가 「10시 2시」가 된다(이 저장소의 「줄였으면 줄였다고 말한다」와
 * 같은 규칙 · DS 38-x). 탭은 보통 공백으로 내린다: 줄을 만들지는 않지만 머리의 들여쓰기
 * (「  - 」·「  [고객] 」)를 흉내 낼 수 있다.
 */
export function oneLine(s: unknown): string {
  return String(s ?? '')
    .replace(/(?:\r\n?|\n)+/g, ` ${LINE_BREAK_MARK} `)
    .replace(/\t+/g, ' ')
    .trim();
}
