/**
 * 「언제부터 무엇까지 들고 있는가」 — 보관 한도에 걸린 기록이 **빠졌다고 말하는** 한 곳 (DS 48-1).
 *
 * 이 제품의 기록은 전부 링버퍼다(대화 500건·변경 이력 500건). 한도를 넘기면 가장 오래된 것이
 * 말없이 버려지고, 재기동하면 통째로 빈다. 그래서 수를 보여 주는 자리는 **그 수의 모수**를
 * 함께 말해야 한다 — 「그 날 0건」과 「그 날 기록 없음」은 전혀 다른 사실이다.
 *
 * 43차 재감사(DS 43-1)가 대화 기록에 세운 규칙인데, 정작 **「누가 무엇을 바꿨는가」의 증거**인
 * 변경 이력에는 세우지 않았다. 변경 이력은 화면이 「최근 100건」이라고만 적었고(그 100건이
 * 서버가 들고 있는 것의 전부인지 일부인지 말하지 않았다), 내려받은 파일은 한도를 한 글자도
 * 말하지 않아 받는 사람이 **전체 이력으로 읽었다**.
 *
 * 문장을 여기 한곳에 둔 이유: 같은 사실을 두 파일이 다르게 적으면, 두 파일을 나란히 받은
 * 사람은 어느 쪽 기준을 믿어야 하는지 알 수 없다(DS 40-1 의 시각 기준 주석과 같은 규칙).
 */
import { josa } from '@/lib/refusal';
import { kstDateTime } from '@/lib/kst';

/** 보관 범위 — 대화 기록(`turnRetention`)·변경 이력(`auditRetention`)이 같은 모양으로 답한다. */
export interface RetentionInfo {
  /** 보관 한도(건). */
  limit: number;
  /** 지금 보관 중인 건수. */
  kept: number;
  /** 이 시각 이후만 담겨 있다(ISO). 그 앞은 「0건」이 아니라 **모른다**. */
  knownFrom: string;
  /** 한도에 걸려 이미 버린 기록이 있는가. */
  dropped: boolean;
}

/**
 * 내려받는 파일 꼬리에 적는 모수 안내 — 대화 기록 CSV·변경 이력 CSV 가 같은 틀을 쓴다.
 *
 * @param noun 받는 사람이 그 파일에서 세는 것의 이름(「대화」·「관리 작업」). 조사는 붙이지
 *   않는다 — 받침에 맞춰 여기서 고른다(`josa` · 화면에 「은(는)」을 남기지 않는다).
 */
export function retentionNotes(noun: string, r: RetentionInfo): string[] {
  return [
    `보관 중인 ${noun} ${r.kept}건을 담았습니다(보관 한도 ${r.limit}건). 그보다 오래된 ${josa(noun, '은', '는')} 이 파일에도 없습니다.`,
    `${kstDateTime(r.knownFrom)} 이후의 기록만 담겨 있습니다 — 그보다 앞선 날이 비어 있는 것은 「${noun} 0건」이 아니라 「기록 없음」입니다.`,
  ];
}
